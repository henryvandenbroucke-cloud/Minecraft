/**
 * Generates docs/PARITY_MATRIX.md and docs/parity-matrix.csv from the registries.
 * Nothing here is hand-written: the matrix is a view over data/registries, so it cannot drift from the data.
 * Run with: npm run parity
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { RegistryDoc, RegistryRecord } from '../src/sim/registry';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const regDir = join(ROOT, 'data', 'registries');

interface Row {
  registry: string;
  id: string;
  name: string;
  status: string;
  confidence: string;
  gate: string;
  tests: string;
  source: string;
}

const rows: Row[] = [];
for (const file of readdirSync(regDir).filter((f) => f.endsWith('.json')).sort()) {
  const doc = JSON.parse(readFileSync(join(regDir, file), 'utf8')) as RegistryDoc;
  for (const r of doc.records) {
    const src = Array.isArray(r.source) ? r.source.join('; ') : r.source;
    rows.push({
      registry: doc.registry,
      id: r.id,
      name: r.name,
      status: r.status,
      confidence: r.confidence,
      gate: Array.isArray(r.edition_gate) ? r.edition_gate.join('|') : '',
      tests: (r.test_ids ?? []).join(' '),
      source: src,
    });
  }
}

const count = (pred: (r: Row) => boolean) => rows.filter(pred).length;
const statuses = ['unresearched', 'researched', 'implemented', 'tested', 'blocked'];
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

const md: string[] = [];
md.push('# Parity matrix (generated)');
md.push('');
md.push('Generated by `npm run parity` from `data/registries/*.json`. Do not edit by hand.');
md.push('');
md.push('Status meanings: **unresearched** (no verified data), **researched** (sourced but not built), **implemented** (code exists and has tests), **tested** (tests run in the reporting build), **blocked** (named blocker).');
md.push('Confidence: **published** (official/dated source), **observed** (measured in reference), **provisional** (designer value), **unknown**.');
md.push('');
md.push('## Totals by registry');
md.push('');
md.push('| Registry | Records | ' + statuses.join(' | ') + ' |');
md.push('|---|---:|' + statuses.map(() => '---:').join('|') + '|');
const registries = [...new Set(rows.map((r) => r.registry))];
for (const reg of registries) {
  const inReg = rows.filter((r) => r.registry === reg);
  md.push(`| ${reg} | ${inReg.length} | ` + statuses.map((s) => inReg.filter((r) => r.status === s).length).join(' | ') + ' |');
}
md.push(`| **all** | ${rows.length} | ` + statuses.map((s) => count((r) => r.status === s)).join(' | ') + ' |');
md.push('');
md.push('## Systems');
md.push('');
md.push('| ID | System | Status | Confidence | Tests | Source |');
md.push('|---|---|---|---|---|---|');
for (const r of rows.filter((x) => x.registry === 'systems')) {
  md.push(`| ${r.id} | ${esc(r.name)} | ${r.status} | ${r.confidence} | ${r.tests || '—'} | ${esc(r.source)} |`);
}
md.push('');
for (const reg of registries.filter((r) => r !== 'systems')) {
  md.push(`## ${reg}`);
  md.push('');
  md.push('| ID | Name | Status | Confidence | Gate | Tests | Source |');
  md.push('|---|---|---|---|---|---|---|');
  for (const r of rows.filter((x) => x.registry === reg)) {
    md.push(`| ${r.id} | ${esc(r.name)} | ${r.status} | ${r.confidence} | ${r.gate || '—'} | ${r.tests || '—'} | ${esc(r.source)} |`);
  }
  md.push('');
}
md.push('## Asset readiness (separate from feature status, brief §3 and §5)');
md.push('');
md.push('| Asset family | Readiness | Notes |');
md.push('|---|---|---|');
md.push('| Buildings, roads, ground | placeholder (procedural boxes, original) | Final modular city kit not started |');
md.push('| Protagonist and car models | placeholder (blocky primitives, original) | No rig, no animation set |');
md.push('| Audio | none | No engine, footstep, music, or dialogue assets |');
md.push('| Dialogue, cinematics, names | none | Not authored |');
md.push('| Reference assets | not used | Policy: no extracted or copied Rockstar assets |');
md.push('');

writeFileSync(join(ROOT, 'docs', 'PARITY_MATRIX.md'), md.join('\n'));

const csv = ['registry,id,name,status,confidence,edition_gate,test_ids,source'];
for (const r of rows) {
  const q = (s: string) => `"${s.replace(/"/g, '""')}"`;
  csv.push([r.registry, r.id, q(r.name), r.status, r.confidence, q(r.gate), q(r.tests), q(r.source)].join(','));
}
writeFileSync(join(ROOT, 'docs', 'parity-matrix.csv'), csv.join('\n') + '\n');
console.log(`wrote docs/PARITY_MATRIX.md and docs/parity-matrix.csv (${rows.length} rows)`);
